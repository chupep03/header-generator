const vscode = require('vscode');
const fs = require('fs');
const path = require('path');

function activate(context) {
    let analyzeCommand = vscode.commands.registerCommand('code-generator.analyzeAndGenerateHeader', function () {
        const editor = vscode.window.activeTextEditor;
        if (!editor) {
            vscode.window.showErrorMessage('No active editor!');
            return;
        }

        const document = editor.document;
        const filePath = document.fileName;
        const fileContent = document.getText();
        
        generateHeaderFromCode(filePath, fileContent);
    });

    context.subscriptions.push(analyzeCommand);
}

function generateHeaderFromCode(filePath, fileContent) {
    try {
        const functions = ExtractFunctions(fileContent);
        const classes = ExtractClasses(fileContent);
        const structs = ExtractStructs(fileContent);
        const includes = ExtractIncludes(fileContent);

        const headerContent = generateHeaderContent(
            path.basename(filePath),
            includes,
            functions,
            classes,
            structs
        );

        saveHeaderFile(filePath, headerContent);
        
    } catch (error) {
        vscode.window.showErrorMessage(`Ошибка анализа: ${error.message}`);
    }
}

function ExtractFunctions(code) {
    const functionTemplate = /(\w+)\s+(\w+)\s*\(([^)]*)\)\s*\{/g;
    const functions = [];
    let match;

    while ((match = functionTemplate.exec(code)) !== null) {
        if (match[2] === 'main') continue;
        
        functions.push({
            name: match[2].trim(),
            returnType: match[1].trim(),
            signature: match[0].trim()
        });
    }

    return functions;
}

function ExtractClasses(code) {
    const classRegex = /class\s+([a-zA-Z_][a-zA-Z0-9_]*)\s*\{/g;
    const classes = [];
    let match;

    while ((match = classRegex.exec(code)) !== null) {
        classes.push({
            name: match[1],
        });
    }

    return classes;
}

function ExtractStructs(code) {
    const structTemplate = /struct\s+([a-zA-Z_][a-zA-Z0-9_]*)\s*\{/g;
    const structs = [];
    let match;

    while ((match = structTemplate.exec(code)) !== null) {
        structs.push({
            name: match[1]
        });
    }

    return structs;
}

function ExtractIncludes(code) { 
    const includeTemplate = /#\s*include\s*<[^>]+>/g;
    return code.match(includeTemplate) || [];
}

function generateHeaderContent(fileName, includes, functions, classes, structs) {
    const baseName = fileName.replace(/\.[^/.]+$/, '').toUpperCase();
    const headerGuard = `${baseName}_H_`;

    let content = `// Generated header file from ${fileName}\n// Generated by C++ Header Generator

#ifndef ${headerGuard}
#define ${headerGuard}

`;

    if (includes.length > 0) {
        content += '// Includes\n';
        includes.forEach(include => {
            content += `${include}\n`;
        });
        content += '\n';
    }

    if (classes.length > 0) {
        content += '// Forward declarations\n';
        classes.forEach(cls => {
            content += `class ${cls.name}; \n`;
        });
        content += '\n';
    }

    if (structs.length > 0) {
        content += '// Structures\n';
        structs.forEach(struct => {
            content += `struct ${struct.name};\n`;
        });
        content += '\n';
    }

    if (functions.length > 0) {
        content += '// Function declarations\n';
        functions.forEach(func => {
            const declaration = func.signature
                .replace(/\s*\{[^}]*\}/, ';')
                .replace(/\s*\{$/, ';');  
            content += `${declaration}\n`;
        });
        content += '\n';
    }

    content += `#endif // ${headerGuard}`;

    return content;
}

async function saveHeaderFile(originalFilePath, headerContent) {
    const headerPath = originalFilePath.replace(/\.(cpp|c|cc|cxx)$/, '.h');
    
    try {
        const document = await vscode.workspace.openTextDocument({
            content: headerContent,
            language: 'cpp'
        });
        
        await vscode.window.showTextDocument(document);
        
        const saveOption = await vscode.window.showInformationMessage(
            'Header generated! Save file?',
            'Save',
            'Save As...',
            'Cancel'
        );
        
        if (saveOption === 'Save') {
            await document.save();
            vscode.window.showInformationMessage(`Header saved to ${headerPath}`);
        } else if (saveOption === 'Save As...') {
            const uri = await vscode.window.showSaveDialog({
                defaultUri: vscode.Uri.file(headerPath),
                filters: {
                    'Header Files': ['h', 'hpp'],
                    'All Files': ['*']
                }
            });
            
            if (uri) {
                fs.writeFileSync(uri.fsPath, headerContent);
                vscode.window.showInformationMessage(`Header saved to ${uri.fsPath}`);
            }
        }
        
    } catch (error) {
        vscode.window.showErrorMessage(`Save error: ${error.message}`);
    }
}

function deactivate() {}

module.exports = {
    activate,
    deactivate
};

